import { mkdir, writeFile } from 'node:fs/promises'

const DOFUSDU = 'https://api.dofusdu.de/dofus3/v1'
const DOFUSDB = 'https://api.dofusdb.fr'
const ITEM_TYPES = ['equipment', 'resources', 'consumables']
const CLASSIC_GAME_TYPE_ID = 0
const DEFAULT_SERVER_NAME = 'Kourial'

const GAME_DATA_DIR = new URL('../src/assets/game-data/', import.meta.url)
const SERVERS_FILE = new URL('../src/config/servers.ts', import.meta.url)

async function getJson(url) {
  const response = await fetch(url)
  if (!response.ok) {
    throw new Error(`${response.status} ${response.statusText} — ${url}`)
  }
  return response.json()
}

// The API serves icons at a stable path, so the id alone rebuilds every URL.
function iconId(item) {
  const match = /\/item\/(\d+)-/.exec(item.image_urls?.icon ?? '')
  return match ? Number(match[1]) : null
}

function trimItem(item) {
  const trimmed = {
    id: item.ankama_id,
    name: item.name,
    level: item.level,
    type: item.type?.name ?? 'Unknown',
    icon: iconId(item),
  }
  if (item.recipe?.length) {
    trimmed.recipe = item.recipe.map((ingredient) => [
      ingredient.item_ankama_id,
      ingredient.quantity,
    ])
  }
  return trimmed
}

function serverName(server) {
  return server.name.en.replace(/^\[!]\s*/, '')
}

function renderServersFile(servers, defaultServerId) {
  const entries = servers
    .map(({ id, name }) => `  { id: ${id}, name: '${name}' },`)
    .join('\n')

  return `// Generated by scripts/generate-game-data.mjs — do not edit.
import type { Server } from '@/types/game'

export const SERVERS: readonly Server[] = [
${entries}
]

export const DEFAULT_SERVER_ID = ${defaultServerId}
`
}

async function main() {
  const meta = await getJson(`${DOFUSDU}/meta/version`)

  const items = []
  const counts = {}
  for (const type of ITEM_TYPES) {
    const dump = await getJson(`${DOFUSDU}/en/items/${type}/all`)
    counts[type] = dump.items.length
    for (const item of dump.items) items.push(trimItem(item))
  }
  items.sort((a, b) => a.id - b.id)

  const serverDump = await getJson(`${DOFUSDB}/servers?$limit=50`)
  const servers = serverDump.data
    .filter((server) => server.gameTypeId === CLASSIC_GAME_TYPE_ID)
    .map((server) => ({ id: server.id, name: serverName(server) }))
    .sort((a, b) => a.name.localeCompare(b.name))

  const defaultServer = servers.find((s) => s.name === DEFAULT_SERVER_NAME)
  if (!defaultServer) {
    throw new Error(`Default server ${DEFAULT_SERVER_NAME} is not in the dump`)
  }

  await mkdir(GAME_DATA_DIR, { recursive: true })
  await writeFile(
    new URL('items.json', GAME_DATA_DIR),
    `${JSON.stringify(items)}\n`,
  )
  await writeFile(
    new URL('meta.json', GAME_DATA_DIR),
    `${JSON.stringify(
      {
        gameVersion: meta.version,
        release: meta.release,
        updateStamp: meta.update_stamp,
        generatedAt: new Date().toISOString(),
        source: DOFUSDU,
        itemCounts: counts,
      },
      null,
      2,
    )}\n`,
  )
  await writeFile(SERVERS_FILE, renderServersFile(servers, defaultServer.id))

  console.log(
    `${items.length} items (game ${meta.version}), ${servers.length} servers`,
  )
}

await main()
